# Operasi dasar

x = 9
y = 7


def tambah (x, y):
    return x + y



def kurang (x, y):
    return x - y



def kali (x, y):
    return x * y



def bagi (x, y):
    return x / y



def pangkat (x, y):
    return x ** y


print ("Hasil tambah =", tambah (x, y))

print ("Hasil kurang =", kurang (x, y))

print ("Hasil kali =", kali (x, y))

print ("Hasil bagi =", bagi (x, y))

print ("Hasil pangkat =", pangkat (x, y))


